export type Translations = typeof translations.en | typeof translations.sv;
export const getTranslations = (language: Language): Translations => translations[language];

const valueMaps: Record<Language, Record<string, string>> = {
  en: {},
  sv: {
    red: "röd", yellow: "gul", blue: "blå", white: "vit", black: "svart", green: "grön", orange: "orange", gray: "grå", grey: "grå",
    left: "vänster", right: "höger", near: "nära", far: "långt bort",
  },
};

export function translateDetectedValue(value: string | undefined, language: Language): string | undefined {
  if (!value) return value;
  return valueMaps[language][value.toLowerCase()] ?? value;
}
